// AppClient 运维部分的 IPC 实现（接口见 packages/shared/src/protocol/client/ops.ts，主进程见 apps/desktop/src/main/ops/register.ts）
import type { AppClient, OpsApi, BatchExecResult, DockerListResult, DockerStat, InspectionRun, InspectionSchedule, Runbook, RunbookInput, ScheduleInput } from '@lingshell/shared'

