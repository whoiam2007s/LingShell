// AppClient AI部分的 IPC 实现（接口见 packages/shared/src/protocol/client/ai.ts，主进程见 apps/desktop/src/main/ai/register.ts）
import type { AppClient, AiApi, ApprovalAnswer, AuditEntry, AuthLevel, McpServerInput, McpServerStatus, McpServerSummary, McpToolInfo, NlCommandRequest, PromptTemplate, SessionInfo, SessionMeta, TemplateInput, TrustLevel, UsageCurrency, UsagePrices, UsageRange, UsageSummary, UsageTotals } from '@lingshell/shared'

export function createAiIpc(): AiApi {
  return {
    agent: {
      createSession: (opts?: { title?: string }) => window.electronAPI.invoke('agent:createSession', opts) as Promise<SessionInfo>,
      listSessions: () => window.electronAPI.invoke('agent:listSessions') as Promise<SessionInfo[]>,
      sendTurn: (sessionId: string, prompt: string) => window.electronAPI.invoke('agent:sendTurn', sessionId, prompt) as Promise<void>,
      steer: (sessionId: string, prompt: string, atts?: unknown[]) => window.electronAPI.invoke('agent:steer', sessionId, prompt, atts) as Promise<string>,
      unsteer: (sessionId: string, messageId: string) => window.electronAPI.invoke('agent:unsteer', sessionId, messageId) as Promise<boolean>,
      interruptTurn: (sessionId: string) => window.electronAPI.invoke('agent:interruptTurn', sessionId) as Promise<void>,
      listPersisted: () => window.electronAPI.invoke('agent:listPersisted') as Promise<SessionMeta[]>,
      reconnectSession: (id: string) => window.electronAPI.invoke('agent:reconnectSession', id) as Promise<SessionInfo>,
      deleteSession: (id: string) => window.electronAPI.invoke('agent:deleteSession', id) as Promise<void>,
      renameSession: (id: string, title: string) => window.electronAPI.invoke('agent:renameSession', id, title) as Promise<void>,
      search: (query: string) => window.electronAPI.invoke('agent:search', query) as Promise<{ sessionId: string; snippet: string }[]>,
      setWorkDir: (id: string, workDir: string) => window.electronAPI.invoke('agent:setWorkDir', id, workDir) as Promise<void>,
      resetContext: (id: string, seed?: string) => window.electronAPI.invoke('agent:resetContext', id, seed) as Promise<void>,
      suggestCommand: (req: NlCommandRequest) => window.electronAPI.invoke('agent:suggestCommand', req) as Promise<string>,
      forkSession: (id: string, messageId: string, mode: 'fork' | 'regenerate') => window.electronAPI.invoke('agent:forkSession', id, messageId, mode) as Promise<{ session: SessionInfo; text: string }>,
    },
    auth: {
      decide: (approvalId: string, ans: ApprovalAnswer) => window.electronAPI.invoke('auth:decide', approvalId, ans) as Promise<void>,
      listForSession: (sessionId: string) => window.electronAPI.invoke('auth:listForSession', sessionId) as Promise<{ hostKey: string; level: AuthLevel }[]>,
      grant: (sessionId: string, hostKey: string, level: AuthLevel) => window.electronAPI.invoke('auth:grant', sessionId, hostKey, level) as Promise<void>,
      revoke: (sessionId: string, hostKey: string) => window.electronAPI.invoke('auth:revoke', sessionId, hostKey) as Promise<void>,
      getTrust: (sessionId: string) => window.electronAPI.invoke('auth:getTrust', sessionId) as Promise<TrustLevel>,
      setTrust: (sessionId: string, level: TrustLevel) => window.electronAPI.invoke('auth:setTrust', sessionId, level) as Promise<void>,
    },
    audit: {
      listForSession: (sid: string) => window.electronAPI.invoke('audit:listForSession', sid) as Promise<AuditEntry[]>,
      listRecent: () => window.electronAPI.invoke('audit:listRecent') as Promise<AuditEntry[]>,
      restore: (sid: string, at: string) => window.electronAPI.invoke('audit:restore', sid, at) as Promise<void>,
    },
    templates: {
      list: () => window.electronAPI.invoke('templates:list') as Promise<PromptTemplate[]>,
      save: (input: TemplateInput) => window.electronAPI.invoke('templates:save', input) as Promise<PromptTemplate>,
      delete: (id: string) => window.electronAPI.invoke('templates:delete', id) as Promise<void>,
    },
    mcp: {
      list: () => window.electronAPI.invoke('mcp:list') as Promise<McpServerSummary[]>,
      save: (input: McpServerInput) => window.electronAPI.invoke('mcp:save', input) as Promise<McpServerSummary>,
      delete: (id: string) => window.electronAPI.invoke('mcp:delete', id) as Promise<void>,
      status: () => window.electronAPI.invoke('mcp:status') as Promise<McpServerStatus[]>,
      test: (input: McpServerInput) => window.electronAPI.invoke('mcp:test', input) as Promise<{ ok: boolean; error?: string; tools?: McpToolInfo[] }>,
      setAutoApprove: (id: string, tools: string[]) => window.electronAPI.invoke('mcp:setAutoApprove', id, tools) as Promise<void>,
    },
    usage: {
      summary: (range: UsageRange) => window.electronAPI.invoke('usage:summary', range) as Promise<UsageSummary>,
      session: (sid: string) => window.electronAPI.invoke('usage:session', sid) as Promise<UsageTotals & { currency: UsageCurrency }>,
      getPrices: () => window.electronAPI.invoke('usage:getPrices') as Promise<UsagePrices>,
      savePrices: (p: UsagePrices) => window.electronAPI.invoke('usage:savePrices', p) as Promise<UsagePrices>,
    },
    modelProfiles: {
      test: (p) => window.electronAPI.invoke('modelProfiles:test', p) as ReturnType<AppClient['modelProfiles']['test']>,
      sessionModel: (sid) => window.electronAPI.invoke('agent:getModel', sid) as ReturnType<AppClient['modelProfiles']['sessionModel']>,
      setSessionModel: (sid, pid) => window.electronAPI.invoke('agent:setModel', sid, pid) as ReturnType<AppClient['modelProfiles']['setSessionModel']>,
    },
    skills: {
      list: () => window.electronAPI.invoke('skills:list') as ReturnType<AppClient['skills']['list']>,
      read: (name) => window.electronAPI.invoke('skills:read', name) as ReturnType<AppClient['skills']['read']>,
      save: (input, old) => window.electronAPI.invoke('skills:save', input, old) as Promise<void>,
      remove: (name) => window.electronAPI.invoke('skills:remove', name) as Promise<void>,
      setFlags: (name, flags) => window.electronAPI.invoke('skills:setFlags', name, flags) as Promise<void>,
      pickImport: (kind) => window.electronAPI.invoke('skills:pickImport', kind) as ReturnType<AppClient['skills']['pickImport']>,
      inspect: (p) => window.electronAPI.invoke('skills:inspect', p) as ReturnType<AppClient['skills']['inspect']>,
      commitImport: (token, opts) => window.electronAPI.invoke('skills:commitImport', token, opts) as Promise<string>,
      cancelImport: (token) => window.electronAPI.invoke('skills:cancelImport', token) as Promise<void>,
      openDir: () => window.electronAPI.invoke('skills:openDir') as Promise<void>,
    },
    attachments: {
      pickFiles: () => window.electronAPI.invoke('attach:pickFiles') as Promise<string[]>,
      pickDirs: () => window.electronAPI.invoke('attach:pickDirs') as Promise<string[]>,
      pickImages: () => window.electronAPI.invoke('attach:pickImages') as Promise<string[]>,
      kinds: (paths) => window.electronAPI.invoke('attach:kinds', paths) as ReturnType<AppClient['attachments']['kinds']>,
      imageFile: (p) => window.electronAPI.invoke('attach:imageFile', p) as Promise<string | null>,
      clipboardPaths: () => window.electronAPI.invoke('attach:clipboardPaths') as Promise<string[]>,
      send: (sid, prompt, atts) => window.electronAPI.invoke('attach:send', sid, prompt, atts) as Promise<void>,
      image: (id) => window.electronAPI.invoke('attach:image', id) as Promise<string | null>,
      open: (p) => window.electronAPI.invoke('attach:open', p) as Promise<string | null>,
    },
    turnChanges: {
      list: (sid) => window.electronAPI.invoke('turnChanges:list', sid) as ReturnType<AppClient['turnChanges']['list']>,
      check: (sid, tid, keys) => window.electronAPI.invoke('turnChanges:check', sid, tid, keys) as ReturnType<AppClient['turnChanges']['check']>,
      diff: (sid, tid, key) => window.electronAPI.invoke('turnChanges:diff', sid, tid, key) as ReturnType<AppClient['turnChanges']['diff']>,
      undo: (sid, tid, keys) => window.electronAPI.invoke('turnChanges:undo', sid, tid, keys) as ReturnType<AppClient['turnChanges']['undo']>,
    },
    rollback: {
      check: (sid, at) => window.electronAPI.invoke('rollback:check', sid, at) as ReturnType<AppClient['rollback']['check']>,
      run: (sid, at, ack) => window.electronAPI.invoke('rollback:run', sid, at, ack) as ReturnType<AppClient['rollback']['run']>,
    },
    knowledge: {
      list: () => window.electronAPI.invoke('knowledge:list') as ReturnType<AppClient['knowledge']['list']>,
      save: (input) => window.electronAPI.invoke('knowledge:save', input) as ReturnType<AppClient['knowledge']['save']>,
      remove: (id) => window.electronAPI.invoke('knowledge:remove', id) as Promise<void>,
    },
    chatPlus: {
      digest: (sid) => window.electronAPI.invoke('chatPlus:digest', sid) as Promise<string>,
      search: (q) => window.electronAPI.invoke('chatPlus:search', q) as ReturnType<AppClient['chatPlus']['search']>,
      runShell: (tid, cmd, sid) => window.electronAPI.invoke('chatPlus:runShell', tid, cmd, sid) as ReturnType<AppClient['chatPlus']['runShell']>,
      answerAsk: (id, a) => window.electronAPI.invoke('chatPlus:answerAsk', id, a) as Promise<void>,
    },
    aiLink: {
      predictCommand: (req) => window.electronAPI.invoke('aiLink:predict', req) as Promise<string>,
      summarizeRecording: (id) => window.electronAPI.invoke('aiLink:summarize', id) as ReturnType<AppClient['aiLink']['summarizeRecording']>,
      recordingSummary: (id) => window.electronAPI.invoke('aiLink:summary', id) as ReturnType<AppClient['aiLink']['recordingSummary']>,
    },
    safety: {
      rules: () => window.electronAPI.invoke('safety:rules') as ReturnType<AppClient['safety']['rules']>,
      setGroupRules: (g, t) => window.electronAPI.invoke('safety:setGroupRules', g, t) as Promise<void>,
      setHostRules: (id, t) => window.electronAPI.invoke('safety:setHostRules', id, t) as Promise<void>,
      preview: (sid) => window.electronAPI.invoke('safety:preview', sid) as Promise<boolean>,
      setPreview: (sid, on) => window.electronAPI.invoke('safety:setPreview', sid, on) as Promise<void>,
      approvePlan: (sid, steps) => window.electronAPI.invoke('safety:approvePlan', sid, steps) as Promise<void>,
      sudoLeases: (sid) => window.electronAPI.invoke('safety:sudoLeases', sid) as ReturnType<AppClient['safety']['sudoLeases']>,
      revokeSudo: (sid, hk) => window.electronAPI.invoke('safety:revokeSudo', sid, hk) as Promise<void>,
    },
  }
}
