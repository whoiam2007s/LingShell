export interface HelpBlock {
  h?: string                  // 小标题
  p?: string                  // 段落
  steps?: string[]            // 有序步骤
  tips?: string[]             // 提示 / 注意事项（带灯泡框）
  keys?: [string, string][]   // 快捷键表：[按键, 说明]
}
export interface HelpSection {
  id: string                  // 唯一、稳定（小写字母 / 数字 / -）
  title: string
  icon: LucideIcon
  settings?: SettingsTab      // 有则右上角显示「去设置」，直达该设置页
  blocks: HelpBlock[]
}

export const blockText = (b: HelpBlock) => [b.h, b.p, ...(b.steps ?? []), ...(b.tips ?? []), ...(b.keys ?? []).flat()].filter(Boolean).join('\n')

/** 按空格分词，每个词都要在同一章节（标题或任一块）里出现；不区分大小写。空查询原样返回 */
export function filterHelp(sections: HelpSection[], q: string): HelpSection[] {
  const tokens = q.toLowerCase().split(/\s+/).filter(Boolean)
  if (!tokens.length) return sections
  return sections.filter((s) => {
    const text = [s.title, ...s.blocks.map(blockText)].join('\n').toLowerCase()
    return tokens.every((t) => text.includes(t))
  })
}

